import {build} from 'vite';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const result=await build({configFile:false,root,logLevel:'warn',build:{target:'es2020',write:false,minify:true,lib:{entry:fileURLToPath(new URL('./play-bookmarklet.ts',import.meta.url)),name:'IIDXMemoImporter',formats:['iife']}}});
const output=(Array.isArray(result)?result[0]:result).output.find(o=>o.type==='chunk');
if(!output)throw new Error('Bookmarklet bundle missing');
const license=await readFile(new URL('../public/licenses/iidx-scraping-bookmarklet.txt',import.meta.url),'utf8');
const code='javascript:'+encodeURIComponent(`/* ${license.replace(/\*\//g,'* /')} */\n${output.code.trim()}`);
await writeFile(new URL('../lib/play-bookmarklet-code.ts',import.meta.url),'// Generated by scripts/build-play-bookmarklet.mjs. Do not edit by hand.\nexport const playBookmarklet='+JSON.stringify(code)+';\n');
console.log(`Bookmarklet generated (${code.length} characters).`);
